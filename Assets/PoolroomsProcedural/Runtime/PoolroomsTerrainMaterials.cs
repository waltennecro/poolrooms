using System;
using UnityEngine;
using Poolrooms.Core;

namespace Poolrooms
{
    [CreateAssetMenu(menuName="Poolrooms/Terrain materials",fileName="PoolroomsTerrainMaterials")]
    public sealed class PoolroomsTerrainMaterials : ScriptableObject
    {
        public Material[] ground,interior;
        public Material[] pastelPaint;
        public Material glass,portal;
        public int appearanceVersion;
        public Material roof;
        public Material[] houseInterior;
    }
    public sealed class TerrainMaterialSet
    {
        public readonly Material[] Ground,GroundHigh,Glass,Portal,Roof,Interior;
        public readonly Material[][] Houses=new Material[6][];
        public Material[] ForGround(TerrainVisualQuality quality){return quality==TerrainVisualQuality.High?GroundHigh:Ground;}
        public TerrainMaterialSet(PoolroomsChunk owner)
        {
            var library=Resources.Load<PoolroomsTerrainMaterials>("PoolroomsTerrainMaterials");
            bool saved=library!=null&&Valid(library.ground)&&Valid(library.interior)&&Valid(library.pastelPaint)&&library.glass!=null&&library.portal!=null;
            // Old autogenerated materials are replaced in memory; custom materials/assets are preserved.
            bool refresh=saved&&library.appearanceVersion<34&&IsLegacyDefault(library.ground[0]);
            Ground=saved&&!refresh?library.ground:new[]{Own(owner,CreateGround("Grass",Color.white,.13f)),Own(owner,CreateGround("Gravel",new Color(.92f,.89f,.81f),.16f)),Own(owner,CreateGround("Soil",new Color(1,.94f,.82f),.09f)),null,null,null};
            if(!saved||refresh)Ground[3]=Ground[4]=Ground[5]=Ground[0];
            GroundHigh=(Material[])Ground.Clone();
            if(!saved||refresh||library.appearanceVersion>=34&&Ground[0].name=="Nivel 94 / Grass")
            {
                var layered=CreateLayeredGround();if(layered!=null)GroundHigh[0]=Own(owner,layered);
            }
            Material wood=Own(owner,CreateGround("Wood",Color.white,.24f));
            Material white=Own(owner,CreateGround("Plaster",new Color(.93f,.93f,.88f),.25f));
            Material satin=Own(owner,new Material(white){name="Nivel 94 / satin fittings",enableInstancing=true});
            if(satin.HasProperty("_SmoothnessRemapMin")){satin.SetFloat("_SmoothnessRemapMin",.32f);satin.SetFloat("_SmoothnessRemapMax",.8f);}
            foreach(string p in new[]{"_Smoothness","_Glossiness"})if(satin.HasProperty(p))satin.SetFloat(p,.42f);
            PoolroomsBiomeMaterialFactory.Validate(satin);
            Material cloth=Own(owner,CreateGround("Cloth",new Color(.76f,.79f,.73f),.16f));
            Interior=saved&&Valid(library.houseInterior)?library.houseInterior:new[]{wood,wood,Own(owner,CreateGround("Plaster",new Color(.94f,.92f,.86f),.2f)),satin,white,cloth};
            Roof=Repeat(saved&&library.roof!=null?library.roof:Own(owner,CreateGround("Roof",Color.white,.22f)));Roof[(int)Surface.Tile]=wood;
            for(int i=0;i<6;i++)
            {
                if(saved&&!refresh){Houses[i]=(Material[])library.interior.Clone();Houses[i][(int)Surface.Plaster]=library.pastelPaint[i];if(library.roof!=null)Houses[i][(int)Surface.Accent]=library.roof;}
                else Houses[i]=new[]{wood,Roof[(int)Surface.Accent],Own(owner,CreateGround("Clapboard",Paint(i),.22f)),white,white,cloth};
            }
            Glass=Repeat(saved?library.glass:Own(owner,PoolroomsBiomeMaterialFactory.Create(SurfaceTheme.Glass,Surface.Glow)));
            Portal=Repeat(saved?library.portal:Own(owner,CreatePortal()));
        }
        private static bool IsLegacyDefault(Material m)
        {
            if(m.name!="Nivel 94 / Grass")return false;
            string p=m.HasProperty("_BaseColor")?"_BaseColor":"_Color";
            return m.HasProperty(p)&&(m.GetColor(p)-new Color(.7f,.84f,.5f,1)).maxColorComponent<.001f&&
                (new Color(.7f,.84f,.5f,1)-m.GetColor(p)).maxColorComponent<.001f;
        }
        private static bool Valid(Material[] a){if(a==null||a.Length!=6)return false;foreach(var m in a)if(m==null)return false;return true;}
        private static Material Own(PoolroomsChunk owner,Material material){owner.ownedMaterials.Add(material);return material;}
        private static Material[] Repeat(Material m){return new[]{m,m,m,m,m,m};}
        public static Color Paint(int i)
        {return new[]{new Color(.92f,.86f,.56f),new Color(.87f,.9f,.83f),new Color(.73f,.82f,.71f),new Color(.8f,.86f,.88f),new Color(.92f,.84f,.76f),new Color(.91f,.9f,.84f)}[Mathf.Clamp(i,0,5)];}
        public static Material CreateGround(string set,Color color,float smooth)
        {
            var m=PoolroomsBiomeMaterialFactory.Create(SurfaceTheme.Hotel,Surface.Tile);
            m.name="Nivel 94 / "+set;m.enableInstancing=true;
            foreach(string n in new[]{"_BaseColor","_Color"})if(m.HasProperty(n))m.SetColor(n,color);
            foreach(string n in new[]{"_Smoothness","_Glossiness"})if(m.HasProperty(n))m.SetFloat(n,smooth);
            Texture2D mask=null;
            foreach(string suffix in new[]{"Albedo","Normal","Mask"})
            {
                var tex=Resources.Load<Texture2D>("PoolroomsTerrainTextures/"+set+"_"+suffix);if(suffix=="Mask")mask=tex;
                string[] props=suffix=="Albedo"?new[]{"_BaseColorMap","_BaseMap","_MainTex"}:suffix=="Normal"?new[]{"_NormalMap","_BumpMap"}:new[]{"_MaskMap"};
                foreach(var prop in props)if(m.HasProperty(prop)){m.SetTexture(prop,tex);if(set=="Cloth")m.SetTextureScale(prop,new Vector2(8,8));}
            }
            // The alpha of an HDRP mask already contains physical smoothness: do not multiply it twice.
            if(m.HasProperty("_SmoothnessRemapMax"))m.SetFloat("_SmoothnessRemapMax",mask!=null?1:smooth);
            if(m.HasProperty("_SmoothnessRemapMin"))m.SetFloat("_SmoothnessRemapMin",0);
            if(m.HasProperty("_NormalScale"))m.SetFloat("_NormalScale",set=="Grass"?.8f:.45f);
            if(m.HasProperty("_BumpScale"))m.SetFloat("_BumpScale",.45f);
            foreach(string p in new[]{"_Metallic","_MetallicRemapMax"})if(m.HasProperty(p))m.SetFloat(p,0);
            foreach(string p in new[]{"_EmissiveColor","_EmissionColor"})if(m.HasProperty(p))m.SetColor(p,Color.black);
            m.DisableKeyword("_EMISSION");PoolroomsBiomeMaterialFactory.Validate(m);return m;
        }
        public static Material CreateLayeredGround()
        {
            var template=Resources.Load<Material>("PoolroomsTerrainLayeredTemplate");
            if(template!=null)return new Material(template){name="Nivel 94 / layered meadow",enableInstancing=true};
            Shader shader=Shader.Find("HDRP/LayeredLit");if(shader==null)return null;
            var m=new Material(shader){name="Nivel 94 / layered meadow",enableInstancing=true};
            m.SetFloat("_LayerCount",2);m.SetFloat("_VertexColorMode",1);
            for(int i=0;i<2;i++)
            {
                string set=i==0?"Grass":"Soil";
                m.SetColor("_BaseColor"+i,i==0?Color.white:new Color(.87f,.85f,.74f));
                m.SetFloat("_Metallic"+i,0);m.SetFloat("_MetallicRemapMax"+i,0);
                m.SetFloat("_SmoothnessRemapMin"+i,0);m.SetFloat("_SmoothnessRemapMax"+i,1);
                m.SetFloat("_NormalScale"+i,.65f);
                foreach(string suffix in new[]{"Albedo","Normal","Mask"})
                {
                    string prop=(suffix=="Albedo"?"_BaseColorMap":suffix=="Normal"?"_NormalMap":"_MaskMap")+i;
                    m.SetTexture(prop,Resources.Load<Texture2D>("PoolroomsTerrainTextures/"+set+"_"+suffix));
                    if(i==1)m.SetTextureScale(prop,new Vector2(1.43f,1.43f));
                }
            }
            PoolroomsBiomeMaterialFactory.Validate(m);
            // Also set native keywords when no HDRP validation hook is loaded yet.
            m.EnableKeyword("_LAYER_MASK_VERTEX_COLOR_MUL");
            for(int i=0;i<2;i++){m.EnableKeyword("_NORMALMAP"+i);m.EnableKeyword("_NORMALMAP_TANGENT_SPACE"+i);m.EnableKeyword("_MASKMAP"+i);}
            return m;
        }
        public static Material CreatePortal()
        {
            Shader shader=Shader.Find("HDRP/Unlit")??Shader.Find("Universal Render Pipeline/Unlit")??Shader.Find("Unlit/Color");
            if(shader==null)throw new InvalidOperationException("No unlit shader for the terrain doorway.");
            var m=new Material(shader){name="Nivel 94 / black doorway",enableInstancing=true};
            foreach(string p in new[]{"_UnlitColor","_BaseColor","_Color"})if(m.HasProperty(p))m.SetColor(p,Color.black);
            foreach(string p in new[]{"_CullMode","_CullModeForward"})if(m.HasProperty(p))m.SetFloat(p,0);
            PoolroomsBiomeMaterialFactory.Validate(m);return m;
        }
    }
}
