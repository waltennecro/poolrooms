"""Fetch pinned CC BY 3.0 Lorc icons and rasterize menu previews, not 3D models.

Requires Inkscape only to recreate PNGs; validation itself is standard-library Python.
Original SVGs remain outside Assets so Unity does not require an SVG importer.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib
import json
import subprocess
import tempfile
import urllib.request
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'Sources/Wings'
DEST=ROOT/'Assets/PoolroomsProcedural/Resources/WingSources'
REVISION='82d948812bfe3f269ef8f731dcdb07b08160edc4'
ICONS=['angel-wings','fluffy-wing','feathered-wing','bat-wing','batwing-emblem','butterfly','dragonfly','steelwing-emblem','lightning-helix','winged-emblem','curly-wing','cog']

def record(data):
    return {'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}

def main():
    SOURCE.mkdir(parents=True,exist_ok=True)
    (DEST/'Icons').mkdir(parents=True,exist_ok=True)
    (DEST/'Licenses').mkdir(parents=True,exist_ok=True)
    urls={name+'.svg':f'https://raw.githubusercontent.com/game-icons/icons/{REVISION}/lorc/{name}.svg' for name in ICONS}
    urls['upstream_license.txt']=f'https://raw.githubusercontent.com/game-icons/icons/{REVISION}/license.txt'
    # SPDX hosts the unmodified CC legal text; pin its release separately.
    urls['CC-BY-3.0.txt']='https://raw.githubusercontent.com/spdx/license-list-data/v3.26.0/text/CC-BY-3.0.txt'
    def fetch(item):
        name,url=item
        data=urllib.request.urlopen(url,timeout=45).read()
        (SOURCE/name).write_bytes(data)
        return name,dict(url=url,**record(data))
    with ThreadPoolExecutor(max_workers=4) as workers:
        locked=dict(workers.map(fetch,urls.items()))
    (SOURCE/'sources.lock.json').write_text(json.dumps(locked,indent=2)+'\n')
    for name in ICONS:
        document=ET.fromstring((SOURCE/(name+'.svg')).read_bytes())
        # All twelve originals include a black 512-square background. Preserve
        # the foreground paths and render on transparent for the dark menu.
        first=list(document)[0]
        if first.attrib.get('d')=='M0 0h512v512H0z':document.remove(first)
        with tempfile.TemporaryDirectory(prefix='wing-icon-') as temp:
            path=Path(temp)/'preview.svg';path.write_bytes(ET.tostring(document))
            subprocess.run(['inkscape',str(path),'--export-type=png','--export-width=192','--export-height=192','--export-filename='+str(DEST/'Icons'/(name+'.png'))],check=True,capture_output=True)
    for name in ['upstream_license.txt','CC-BY-3.0.txt']:
        (DEST/'Licenses'/name).write_bytes((SOURCE/name).read_bytes())
    notice=('Icons made by Lorc, https://lorcblog.blogspot.com/, via https://game-icons.net/.\n'
            'Source: https://github.com/game-icons/icons/tree/'+REVISION+'/lorc\n'
            'License: Creative Commons Attribution 3.0 Unported (CC-BY-3.0).\n'
            'https://creativecommons.org/licenses/by/3.0/\n'
            'Changes: black backgrounds removed; SVGs rendered to transparent 192px menu PNGs.\n'
            'No endorsement implied. Original SVGs and source hashes: Sources/Wings.\n'
            'These 12 external icons are used in the Skins > Wings selector. They are not 3D models.\n'
            'The 144 volumetric wing constructions are new project geometry generated by Core/WingCatalog.cs,\n'
            'not external model downloads; the repository does not grant a blanket licence to unrelated game code.\n')
    (DEST/'Licenses/NOTICE.txt').write_text(notice)
    catalog={'sourceRevision':REVISION,'sourceAuthor':'Lorc','sourceLicense':'CC-BY-3.0','distinctExternalIcons':12,
             'distinctExternal3DModels':0,'originalGeometryVariants':144,'geometryFamilies':12,
             'paletteSwapsCountAsDesigns':False,'nativeUnityValidated':False,
             'icons':[{'id':name,'resource':'WingSources/Icons/'+name,'sourceUrl':urls[name+'.svg'],'sourceSha256':locked[name+'.svg']['sha256']} for name in ICONS]}
    (DEST/'catalog.json').write_text(json.dumps(catalog,indent=2)+'\n')
    hashes={p.relative_to(DEST).as_posix():record(p.read_bytes()) for p in sorted(DEST.rglob('*')) if p.is_file() and p.name!='files.sha256.json'}
    (DEST/'files.sha256.json').write_text(json.dumps(hashes,indent=2)+'\n')
    print('Imported 12 pinned CC BY 3.0 menu icons, legal texts, source locks and PNGs; 0 downloaded 3D wing models.')

if __name__=='__main__':main()
